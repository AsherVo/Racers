using System.Text;
using Engine;

// Maps every data ID to its group (the folder it sits in) as C#, ordered by the Compee project's rows.
// Data files missing from the rows go last. Usage: DataGroups <Project.comp> <output.cs>

const int SUCCESS = 0;
const int FAILURE = 1;
const int USAGE = 2;

if ( args.Length != 2 )
{
    Console.Error.WriteLine( "Usage: DataGroups <Project.comp> <output.cs>" );
    return USAGE;
}

string projectPath = args[0];
string outputPath = args[1];

YamlMap project;
try
{
    project = Yaml.Parse( File.ReadAllText( projectPath ), projectPath ) as YamlMap
        ?? throw new YamlException( new YamlError( "Expected a map at the top level.", 1, 1, source: projectPath ) );
}
catch ( YamlException exception )
{
    foreach ( var error in exception.errors )
        Console.Error.WriteLine( $"error: {error}" );

    return FAILURE;
}

if ( !project.TryGetValue( "data", out var dataNode ) || dataNode is not YamlScalar dataScalar )
{
    Console.Error.WriteLine( $"error: {projectPath} has no 'data' folder." );
    return FAILURE;
}

string dataDirectory = Path.Combine( Path.GetDirectoryName( Path.GetFullPath( projectPath ) )!, dataScalar.value );
if ( !Directory.Exists( dataDirectory ) )
{
    Console.Error.WriteLine( $"error: Data folder '{dataDirectory}' does not exist." );
    return FAILURE;
}

var rows = project.TryGetValue( "rows", out var rowsNode ) && rowsNode is YamlList rowList
    ? rowList.OfType< YamlScalar >().Select( row => row.value ).ToList()
    : [];

var groupsById = new Dictionary< string, string >();
var foundIds = new List< string >();
var errors = new List< string >();

foreach ( string file in Directory.EnumerateFiles( dataDirectory, "*.yaml" ) )
    errors.Add( $"'{Path.GetFileName( file )}' isn't in a group folder. Move it into one of the folders in {dataDirectory}." );

foreach ( string groupDirectory in Directory.EnumerateDirectories( dataDirectory ).Order( StringComparer.Ordinal ) )
{
    string group = Path.GetFileName( groupDirectory );
    foreach ( string file in Directory.EnumerateFiles( groupDirectory, "*.yaml" ).Order( StringComparer.Ordinal ) )
    {
        string id = Path.GetFileNameWithoutExtension( file );
        if ( groupsById.TryGetValue( id, out var existingGroup ) )
        {
            errors.Add( $"Data ID '{id}' is in both {existingGroup}/ and {group}/. Data IDs must be unique." );
            continue;
        }

        groupsById[id] = group;
        foundIds.Add( id );
    }
}

if ( errors.Count > 0 )
{
    foreach ( string error in errors )
        Console.Error.WriteLine( $"error: {error}" );

    return FAILURE;
}

var orderedIds = rows.Where( groupsById.ContainsKey ).Distinct().ToList();
var unlistedIds = foundIds.Except( orderedIds ).ToList();
orderedIds.AddRange( unlistedIds );

foreach ( string id in unlistedIds )
    Console.WriteLine( $"'{id}' isn't in the rows of {projectPath}, so it goes last." );

var builder = new StringBuilder();
builder.AppendLine( "// <auto-generated />" );
builder.AppendLine( "// Written by tools/DataGroups, in the order of Project.comp's rows." );
builder.AppendLine( "namespace Racers;" );
builder.AppendLine();
builder.AppendLine( "public partial class Data" );
builder.AppendLine( "{" );
builder.AppendLine( "    static readonly Dictionary< string, Group > GroupsById = new()" );
builder.AppendLine( "    {" );
foreach ( string id in orderedIds )
    builder.AppendLine( $"        {{ \"{id}\", Group.{groupsById[id]} }}," );

builder.AppendLine( "    };" );
builder.AppendLine( "}" );

string code = builder.ToString();
bool unchanged = File.Exists( outputPath ) && File.ReadAllText( outputPath ) == code;
if ( !unchanged )
{
    Directory.CreateDirectory( Path.GetDirectoryName( Path.GetFullPath( outputPath ) )! );
    File.WriteAllText( outputPath, code );
}

Console.WriteLine( $"{orderedIds.Count} data IDs {( unchanged ? "unchanged in" : "written to" )} {outputPath}" );
return SUCCESS;
